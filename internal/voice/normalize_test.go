package voice

import (
	"strings"
	"testing"
)

// Кейсы из реального фидбека владельца на релиз 2026.14: дребезг голоса,
// «два ТОЧКА пятьдесят шесть», «- CPU:», GiB/CPU/RAM по буквам, эмодзи.
func TestNormalizeForSpeech(t *testing.T) {
	cases := []struct{ in, want string }{
		// десятичные числа — главный фидбек
		{"load average 2.56", "load average 2 и 56"},
		{"Загрузка 76%, la 2.56", "Загрузка 76 процентов, la 2 и 56"},
		{"71.7% занято", "71 и 7 процентов занято"},
		{"нужно 1,5 гигабайта", "нужно 1 и 5 гигабайта"},
		{"память 0.9", "память 0 и 9"},

		// единицы и аббревиатуры
		{"Свободно 5.2 GiB из 11.6 GiB", "Свободно 5 и 2 гигабайт из 11 и 6 гигабайт"},
		{"RAM: 3.1 GiB / 11.6 GiB", "память: 3 и 1 гигабайт / 11 и 6 гигабайт"},
		{"CPU 71.7%, RAM 48%", "процессор 71 и 7 процентов, память 48 процентов"},
		{"диск 120 GB", "диск 120 гигабайт"},
		{"кэш 512 MB", "кэш 512 мегабайт"},
		{"частота 2.3 GHz", "частота 2 и 3 гигагерц"},
		{"SSD почти полон", "твердотельный диск почти полон"},

		// списки и markdown
		{"- CPU: 12%\n- RAM: 40%", "процессор: 12 процентов\nпамять: 40 процентов"},
		{"**Внимание**: сервис упал", "Внимание: сервис упал"},
		{"см. `journalctl -u archi`", "см. journalctl -u archi"},
		{"### Отчёт по нодам", "Отчёт по нодам"},
		{"[документация](https://example.com/docs) доступна", "документация доступна"},
		{"| нода | статус |\n| local | ок |", ", нода, статус,\n, local, ок,"},

		// URL → «ссылка»
		{"логи тут: https://example.com/log?x=1", "логи тут: ссылка"},
		{"www.foo.bar/text", "ссылка"},

		// диапазоны, стрелки, время
		{"нагрузка выросла 10-20 пунктов", "нагрузка выросла 10 — 20 пунктов"},
		{"CPU -> RAM", "процессор — память"},
		{"в 15:04 старт", "в 15 04 старт"},

		// эмодзи и прочий мусор
		{"✅ Всё работает 🟡 есть предупреждения", "Всё работает есть предупреждения"},
		{"🌡️ жара ~30°C", "жара примерно 30 градусов"},

		// идемпотентность
		{"load average 2 и 56", "load average 2 и 56"},

		// пустое и чистое
		{"", ""},
		{"  ", ""},
		{"всё в порядке", "всё в порядке"},
	}
	for _, c := range cases {
		if got := NormalizeForSpeech(c.in); got != c.want {
			t.Errorf("NormalizeForSpeech(%q)\n  получили %q\n  хотели  %q", c.in, got, c.want)
		}
	}
}

func TestNormalizeListMarkers(t *testing.T) {
	// маркеры срезаются, аббревиатуры внутри строки разворачиваются
	got := NormalizeForSpeech("- CPU: 12%\n- RAM: 40%\n1. диск ок")
	want := "процессор: 12 процентов\nпамять: 40 процентов\nдиск ок"
	if got != want {
		t.Errorf("списки: получили %q, хотели %q", got, want)
	}
}

func TestSpeechChunks(t *testing.T) {
	// короткий текст — одна фраза
	if got := SpeechChunks("Всё в порядке. Нагрузка в норме.", 200); len(got) != 2 {
		t.Errorf("хочу 2 фразы, получил %d: %q", len(got), got)
	}
	// «1.5» не разрезается как граница предложения
	got := SpeechChunks("нужно 1.5 гигабайта места", 200)
	if len(got) != 1 || got[0] != "нужно 1.5 гигабайта места" {
		t.Errorf("десятичная дробь разрезана: %q", got)
	}
	// длинная фраза режется на куски ≤ maxRunes
	long := strings.Repeat("очень длинное предложение, ", 40)
	got = SpeechChunks(long, 100)
	if len(got) < 2 {
		t.Fatalf("длинная фраза не разрезана: %d кусков", len(got))
	}
	for _, c := range got {
		if len([]rune(c)) > 130 { // запас на границу+запятую
			t.Errorf("кусок длиннее лимита: %d рун", len([]rune(c)))
		}
	}
	// пустой вход
	if got := SpeechChunks("   ", 200); got != nil {
		t.Errorf("пустой вход должен дать nil, дал %q", got)
	}
}
